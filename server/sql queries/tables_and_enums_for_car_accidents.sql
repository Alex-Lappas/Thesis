-- Enum Definitions
CREATE TYPE enum_gender AS ENUM ('Men', 'Female');
CREATE TYPE enum_age_group AS ENUM ('0-14', '15-17', '18-20', '21-24', '25-44', '45-64', '>65', 'Unknown');
CREATE TYPE enum_person_category AS ENUM ('Drivers', 'Passengers', 'Pedestrians');
CREATE TYPE enum_day_of_week AS ENUM ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday');
CREATE TYPE enum_month AS ENUM ('January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December');
CREATE TYPE enum_hour_of_accident AS ENUM ('0-4', '5-8', '9-12', '13-16', '17-20', '21-23');
CREATE TYPE enum_accident_severity AS ENUM ('Fatal', 'Non-fatal');
CREATE TYPE enum_road_type AS ENUM ('Motorway', 'National road', 'Provincial road', 'Municipal Road', 'Other/Unknown');
CREATE TYPE enum_area AS ENUM ('Inside residential areas', 'Outside residential areas');
CREATE TYPE enum_means_of_transport AS ENUM ('Passenger cars', 'Motorcycles', 'Moped', 'Bicycles', 'Light goods vehicles up to 3.5t', 'Heavy goods vehicles over 3.5t', 'Buses', 'Other type of vehicle', 'Pedestrians');
CREATE TYPE enum_greek_regions AS ENUM ('Anatoliki Makedonia, Thraki', 'Kentriki Makedonia', 'Dytiki Makedonia ', 'Ipeiros', 'Thessalia', 'Ionioi Nisoi', 'Dytiki Ellas', 'Sterea Ellas', 'Attiki', 'Peloponnisos', 'Voreio Aigaio', 'Notio Aigaio', 'Kriti');

-- Tables
CREATE TABLE accidents_by_severity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year INT NOT NULL,
    severity enum_accident_severity NOT NULL,
    value INT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
COMMENT ON TABLE accidents_by_severity IS 'Stores annual accident counts by severity (Fatal, Non-fatal).';

CREATE TABLE total_accidents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year INT NOT NULL,
  value INT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
